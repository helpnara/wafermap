#: 전체 용어 목록
ALL_TERMS: tuple[Term, ...] = (
    _PRODUCT + _TEST + _PROCESS + _EQUIPMENT
    + _DEFECT_PATTERNS + _STATISTICS + _MACHINE_LEARNING + _DATA
)

_BY_TERM: dict[str, Term] = {t.term: t for t in ALL_TERMS}


# ──────────────────────────────────────────────────────────────────────────
# 조회 API
# ──────────────────────────────────────────────────────────────────────────


def _normalize(text: str) -> str:
    """검색 비교용으로 문자열을 정규화한다.

    소문자화 + 공백/하이픈 제거 + 유니코드 정규화. 'Edge-Ring', 'edge ring',
    '엣지링'이 모두 같은 것으로 취급되게 한다.
    """
    text = unicodedata.normalize("NFKC", text).lower()
    return re.sub(r"[\s\-_·]", "", text)


def all_terms() -> tuple[Term, ...]:
    """전체 용어를 돌려준다."""
    return ALL_TERMS


def categories() -> dict[str, str]:
    """분류 이름 → 설명."""
    return dict(CATEGORIES)


def get(name: str) -> Term | None:
    """정확한 이름 또는 별칭으로 용어 하나를 찾는다."""
    if name in _BY_TERM:
        return _BY_TERM[name]
    key = _normalize(name)
    for term in ALL_TERMS:
        if _normalize(term.term) == key or any(_normalize(a) == key for a in term.aliases):
            return term
    return None


def by_category(category: str) -> tuple[Term, ...]:
    """분류에 속한 용어를 돌려준다."""
    if category not in CATEGORIES:
        raise KeyError(f"알 수 없는 분류: {category!r} (가능: {list(CATEGORIES)})")
    return tuple(t for t in ALL_TERMS if t.category == category)


def search(query: str, *, limit: int = 20) -> tuple[Term, ...]:
    """용어명·별칭·설명 본문까지 훑어 검색한다.

    정렬 순서: 이름 완전일치 → 이름 부분일치 → 별칭 일치 → 본문 포함.
    """
    if not query.strip():
        return ()
    key = _normalize(query)

    exact: list[Term] = []
    name_hit: list[Term] = []
    alias_hit: list[Term] = []
    body_hit: list[Term] = []

    for term in ALL_TERMS:
        name = _normalize(term.term)
        aliases = [_normalize(a) for a in term.aliases]
        if name == key or key in aliases:
            exact.append(term)
        elif key in name:
            name_hit.append(term)
        elif any(key in a for a in aliases):
            alias_hit.append(term)
        elif key in _normalize(term.short + term.plain + term.detail + term.why_matters):
            body_hit.append(term)

    return tuple((exact + name_hit + alias_hit + body_hit)[:limit])


def related_terms(name: str) -> tuple[Term, ...]:
    """관련 용어 객체들을 돌려준다."""
    term = get(name)
    if term is None:
        return ()
    return tuple(t for t in (get(r) for r in term.related) if t is not None)


def find_in_text(text: str, *, min_length: int = 2) -> tuple[Term, ...]:
    """본문에 등장하는 용어를 찾아낸다 (학습노트 자동 링크용).

    왜 필요한가: 학습노트나 화면 설명에 나온 전문용어에 자동으로 사전 링크를 걸어,
        읽다가 막히면 바로 뜻을 확인할 수 있게 한다.

    Args:
        text: 검사할 본문
        min_length: 이 길이 미만의 표기는 무시한다 (오탐 방지)
    """
    found: dict[str, Term] = {}
    normalized = _normalize(text)

    for term in ALL_TERMS:
        candidates = (term.term, *term.aliases)
        for candidate in candidates:
            if len(candidate) < min_length:
                continue
            if _normalize(candidate) in normalized:
                found[term.term] = term
                break
    return tuple(found.values())


def stats() -> dict[str, int]:
    """사전 규모 요약 — 분류별 용어 수."""
    out = {c: len(by_category(c)) for c in CATEGORIES}
    out["합계"] = len(ALL_TERMS)
    return out
